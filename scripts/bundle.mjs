import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';

await mkdir('dist', {recursive: true});
for (const [entry, outfile] of [['src/plugin.ts', 'dist/index.js'], ['src/pi.ts', 'dist/pi.js'], ['src/pi-supervisor.ts', 'dist/pi-supervisor.js']]) await build({entryPoints: [entry], outfile, bundle: true,
  platform: 'node', format: 'esm', target: 'node22', packages: 'external', charset: 'utf8',
  legalComments: 'eof', banner: {js: '// Generated by npm run bundle. Edit src/, not this file.'},
});
