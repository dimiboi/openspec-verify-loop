import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

await mkdir('skills/openspec-verify-loop/scripts',{recursive:true});
await build({entryPoints:['src/cli.ts'],outfile:'skills/openspec-verify-loop/scripts/controller.mjs',bundle:true,
  platform:'node',format:'esm',target:'node22',charset:'utf8',legalComments:'eof',
  banner:{js:'#!/usr/bin/env node\n// Generated by npm run build. Edit src/, not this file.'},
});
await copyFile('LICENSE','skills/openspec-verify-loop/LICENSE');
const mit=await readFile('LICENSE','utf8');
const opencode=mit.replace('Copyright (c) 2026 openspec-verify-loop contributors','Copyright (c) 2025 opencode');
const zod=await readFile('node_modules/zod/LICENSE','utf8');
await writeFile('skills/openspec-verify-loop/references/third-party-licenses.txt',
  `Bundled runtime dependencies\n\n@opencode/client 2.2.5\nhttps://github.com/anomalyco/opencode/blob/dev/LICENSE\n\n${opencode}\n\nZod\nhttps://github.com/colinhacks/zod\n\n${zod}`);
